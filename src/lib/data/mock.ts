function buildLeaderboard(
  seed: Array<[string, string, "barcelona" | "real-madrid", number, number]>,
  currentRank = 27
): LeaderboardEntry[] {
  return seed.map(([username, countryCode, clubId, xp, movement], index) => ({
    rank: index + 1,
    username,
    countryCode,
    clubId,
    xp,
    movement,
    isCurrentUser: index + 1 === currentRank,
  }));
}

